import numpy as np
import cv2

def create_cubesat_silhouette(img_size=64):
    """Draws a simple 2D CubeSat silhouette: square body with rectangular side solar panels."""
    img = np.zeros((img_size, img_size), dtype=np.uint8)
    center = img_size // 2
    body_half = 8
    # Draw core body
    cv2.rectangle(img, (center - body_half, center - body_half),
                  (center + body_half, center + body_half), 255, -1)
    # Draw left & right solar panels
    panel_w = 12
    cv2.rectangle(img, (center - body_half - panel_w, center - 1),
                  (center - body_half, center + 1), 255, -1)
    cv2.rectangle(img, (center + body_half, center - 1),
                  (center + body_half + panel_w, center + 1), 255, -1)
    return img

def create_hubble_silhouette(img_size=64):
    """Draws a Space Telescope (Hubble) silhouette: cylindrical body with long parallel panels."""
    img = np.zeros((img_size, img_size), dtype=np.uint8)
    center = img_size // 2
    # Cylinder body
    cv2.rectangle(img, (center - 12, center - 5), (center + 12, center + 5), 255, -1)
    # Solar panels
    panel_w = 4
    panel_h = 16
    cv2.rectangle(img, (center - 6, center - 5 - panel_h), (center - 6 + panel_w, center - 5), 255, -1)
    cv2.rectangle(img, (center - 6, center + 5), (center - 6 + panel_w, center + 5 + panel_h), 255, -1)
    return img

def create_iss_silhouette(img_size=64):
    """Draws a Space Station (ISS) silhouette: central truss with multiple parallel panel grids."""
    img = np.zeros((img_size, img_size), dtype=np.uint8)
    center = img_size // 2
    # Central long truss line
    cv2.line(img, (center - 20, center), (center + 20, center), 255, 2)
    # Grid of solar panel arrays
    for offset in [-16, -12, 10, 14]:
        cv2.rectangle(img, (center + offset, center - 14), (center + offset + 2, center + 14), 255, -1)
    return img

def apply_optical_degradation(img, noise_std=20, blur_kernel=3, contrast_scale=0.5):
    """Simulates real-world physical sensing degradations."""
    # 1. Attenuate light (lowers contrast)
    degraded = img.astype(float) * contrast_scale

    # 2. Atmospheric Blur (Gaussian Blur)
    if blur_kernel > 1:
        if blur_kernel % 2 == 0:
            blur_kernel += 1  # Kernel size must be odd
        degraded = cv2.GaussianBlur(degraded, (blur_kernel, blur_kernel), 0)

    # 3. Add Sensor Noise (Gaussian distribution)
    noise = np.random.normal(0, noise_std, img.shape)
    degraded = degraded + noise

    # Keep pixel values bounded between 0 and 255
    return np.clip(degraded, 0, 255).astype(np.uint8)